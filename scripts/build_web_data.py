"""Bundle the JSON files in data/ into app/data.js for the static web app.

The app reads its data from a <script> instead of fetch() so that it also works
when index.html is opened straight from disk (file://) and so the page can run
under a CSP that blocks all network requests.

Usage:
    python scripts/build_web_data.py
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
OUT = ROOT / "app" / "data.js"

FILES = {
    "brand": "brand.json",
    "categories": "categories.json",
    "questions": "questions.json",
    "blocks": "blocks.json",
    "audit": "audit_actions.json",
    "pages": "page_scores.json",
    "demo": "demo_monitoring.json",
}


def main() -> None:
    bundle = {key: json.loads((DATA / name).read_text(encoding="utf-8")) for key, name in FILES.items()}
    payload = json.dumps(bundle, ensure_ascii=False, separators=(",", ":"))
    OUT.write_text(
        "/* Generated by scripts/build_web_data.py – do not edit by hand. */\n"
        f"window.GEO_DATA = {payload};\n",
        encoding="utf-8",
    )
    print(f"Wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size:,} bytes)")


if __name__ == "__main__":
    main()
